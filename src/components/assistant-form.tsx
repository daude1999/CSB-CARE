"use client";

import { useActionState } from "react";
import Link from "@/components/link";
import { askAction, type AskState } from "@/app/actions";

const EXAMPLES = ["What changed in the latest safeguarding guidance?", "Which of our policies need updating?", "What actions are needed before approval?", "Which policy reviews are overdue?"];

export function AssistantForm() {
  const [state, action, pending] = useActionState<AskState, FormData>(askAction, { question: "" });
  const r = state.result;
  return (
    <div className="space-y-3">
      <div className="panel space-y-3">
      <h2 className="text-[17px]">Ask a question</h2>
      <form action={action} className="flex gap-2">
        <input name="question" className="input" defaultValue={state.question} placeholder="Ask about your policies, requirements or recent changes" aria-label="Question" maxLength={1000} />
        <button className="btn-primary" type="submit" disabled={pending}>{pending ? "Searching…" : "Ask"}</button>
      </form>
      <div className="flex flex-wrap items-center gap-2 text-[13px] text-slate-600">
        Try: {EXAMPLES.map((e) => <span key={e} className="rounded-full bg-[#e3effb] px-2.5 py-0.5 text-[#1d4f91]">{e}</span>)}
      </div>
      </div>
      {state.error ? <div role="alert" className="rounded-[3px] border-l-4 border-[#e4544f] bg-[#fde1e3] px-4 py-3 text-sm text-[#a3242c]">{state.error}</div> : null}
      {r ? (
        <div className="card space-y-4" data-testid="assistant-answer">
          <div className="flex flex-wrap gap-2 text-xs">
            <span className="rounded bg-amber-50 px-2 py-0.5 text-amber-800">Answer generated by {r.provider}. Check the cited sources.</span>
            {r.simulated ? <span className="rounded bg-violet-50 px-2 py-0.5 text-violet-700">SIMULATED AI</span> : null}
          </div>
          <p className="prose-policy text-sm">{r.answer}</p>
          {r.facts.length ? (
            <div>
              <div className="label">From your records</div>
              <ul className="list-disc pl-5 text-sm">{r.facts.map((f, i) => <li key={i}>{f}</li>)}</ul>
            </div>
          ) : null}
          <div>
            <div className="label">Sources</div>
            {r.citations.length ? (
              <ul className="space-y-2 text-sm">
                {r.citations.map((c, i) => (
                  <li key={i} className="rounded-[2px] bg-[#f5f9fc] p-3">
                    <div className="flex flex-wrap items-center gap-2 text-xs">
                      <span className={c.verified ? "text-emerald-700" : "text-rose-700"}>{c.verified ? "verified quote" : "unverified: disregard"}</span>
                      <span className="text-slate-500">{c.kind === "POLICY" ? "Policy" : "Source"} · {c.legalStatus.replace(/_/g, " ").toLowerCase()} · {c.versionLabel}</span>
                      {c.link !== "#" ? <Link href={c.link}>{c.heading}</Link> : <span>{c.heading}</span>}
                    </div>
                    <blockquote className="mt-1 italic">“{c.quote}”</blockquote>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="muted">No supporting material was found. The assistant cannot answer from evidence it does not have.</p>
            )}
          </div>
          {r.evidenceGaps.length ? (
            <div>
              <div className="label">Evidence gaps</div>
              <ul className="list-disc pl-5 text-sm text-amber-800">{r.evidenceGaps.map((g, i) => <li key={i}>{g}</li>)}</ul>
            </div>
          ) : null}
        </div>
      ) : null}
    </div>
  );
}
