export function actionLabel(action: string) {
  return LABELS[action] ?? action.replace(/[._]/g, " ");
}
/** Events that need attention in lists. */
export function actionTone(action: string): "rose" | "amber" | "slate" | "green" | "violet" {
  if (/suspended|closed|deactivated|blocked|emergency|disabled|revoked/.test(action)) return "rose";
  if (/reset|roles|required|support/.test(action)) return "amber";
  if (/created|reinstated|reactivated|enabled|approved|started/.test(action)) return "green";
  return "slate";
}

const securityWhere = (): Prisma.AuditLogWhereInput => ({ OR: SECURITY_PREFIXES.map((p) => ({ action: { startsWith: p } })) });
export const ACTIVITY_PAGE = 40;

/** The Security Audit and Activity History: platform-wide, filterable by client, person, action and outcome. */
export async function securityAudit(ctx: Ctx, f: { org?: string; q?: string; action?: string; logins?: boolean; page?: number } = {}) {
  requirePlatform(ctx, "platform.view");
  const where: Prisma.AuditLogWhereInput = {
    AND: [
      securityWhere(),
      ...(f.org ? [{ organisationId: f.org }] : []),
      ...(f.action ? [{ action: { startsWith: f.action.slice(0, 80) } }] : []),
      ...(f.logins ? [] : [{ action: { not: "auth.login" } }]),
      ...(f.q ? [{ OR: [{ entityId: f.q.trim() }, { actorId: f.q.trim() }, { data: { path: ["email"], string_contains: f.q.trim().toLowerCase() } }] }] : []),
    ],
  };
  const page = Math.max(1, Math.floor(f.page ?? 1));
  const [total, rows] = await Promise.all([
    db.auditLog.count({ where }),
    db.auditLog.findMany({ where, orderBy: { createdAt: "desc" }, skip: (page - 1) * ACTIVITY_PAGE, take: ACTIVITY_PAGE }),
  ]);
  return { total, page, entries: await describe(rows) };
}

/** A client's own history in its profile. Full activity only while ACTIVITY_LOG support access is active. */
export async function clientAudit(ctx: Ctx, organisationId: string, opts: { full?: boolean; page?: number } = {}) {
  requirePlatform(ctx, "platform.view");
  await requireCustomerOrg(organisationId);
  if (opts.full) await requireSupportScope(ctx, organisationId, "ACTIVITY_LOG");
  const where: Prisma.AuditLogWhereInput = opts.full ? { organisationId } : { AND: [{ organisationId }, securityWhere(), { action: { not: "auth.login" } }] };
  const page = Math.max(1, Math.floor(opts.page ?? 1));
  const [total, rows] = await Promise.all([db.auditLog.count({ where }), db.auditLog.findMany({ where, orderBy: { createdAt: "desc" }, skip: (page - 1) * ACTIVITY_PAGE, take: ACTIVITY_PAGE })]);
  return { total, page, entries: await describe(rows) };
}

/** Significant recent events for the dashboard: account, security, commercial and configuration changes. */
export async function recentActivity(ctx: Ctx, take = 12) {
  requirePlatform(ctx, "platform.view");
  const rows = await db.auditLog.findMany({
    where: { AND: [securityWhere(), { action: { notIn: ["auth.login", "platform.support.used"] } }] },
    orderBy: { createdAt: "desc" },
    take,
  });
  return describe(rows);
}

async function describe(rows: { id: string; action: string; actorId: string | null; organisationId: string | null; entityType: string; entityId: string; data: Prisma.JsonValue; createdAt: Date }[]) {
  const userIds = new Set<string>();
  for (const r of rows) {
    if (r.actorId) userIds.add(r.actorId);
    const d = r.data && typeof r.data === "object" && !Array.isArray(r.data) ? (r.data as Record<string, unknown>) : {};
    if (typeof d.userId === "string") userIds.add(d.userId);
  }
  const orgIds = [...new Set(rows.map((r) => r.organisationId).filter((x): x is string => !!x))];
  const [users, orgs] = await Promise.all([
    db.user.findMany({ where: { id: { in: [...userIds] } }, select: { id: true, name: true } }),
    db.organisation.findMany({ where: { id: { in: orgIds } }, select: { id: true, name: true } }),
  ]);
  const un = new Map(users.map((u) => [u.id, u.name]));
  const on = new Map(orgs.map((o) => [o.id, o.name]));
  return rows.map((r) => {
    const d = r.data && typeof r.data === "object" && !Array.isArray(r.data) ? (r.data as Record<string, unknown>) : {};
    const subjectId = typeof d.userId === "string" ? d.userId : r.entityType === "User" ? r.entityId : null;
    const outcome = d.outcome === "blocked" ? "Blocked" : "Done";
    return {
      id: r.id,
      at: r.createdAt,
      action: r.action,
      label: actionLabel(r.action),
      tone: actionTone(r.action),
      actor: r.actorId ? (un.get(r.actorId) ?? "Unknown person") : automationOf(r.data) ? "CSB AI" : "System",
      actorId: r.actorId,
      organisationId: r.organisationId,
      organisation: r.organisationId ? (on.get(r.organisationId) ?? "Removed organisation") : null,
      subjectId,
      subject: subjectId ? (un.get(subjectId) ?? null) : null,
      entityType: r.entityType,
      outcome,
      reason: typeof d.reason === "string" ? d.reason : null,
      before: d.before ?? null,
      after: d.after ?? null,
    };
  });
}
