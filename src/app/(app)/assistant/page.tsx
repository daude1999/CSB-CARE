import { notFound } from "next/navigation";
import { requireCtx } from "@/server/auth/current";
import { hasOrgPermission } from "@/server/auth/rbac";
import { getAiProvider } from "@/server/ai";
import { AssistantForm } from "@/components/assistant-form";
import { PageHeader } from "@/components/ui";

export const dynamic = "force-dynamic";

export default async function AssistantPage() {
  const ctx = await requireCtx();
  if (!hasOrgPermission(ctx, "assistant.use")) notFound();
  const ai = getAiProvider();
  return (
    <>
      <PageHeader
        eyebrow="Insights · ask your policies"
        title="AI Assistant"
        subtitle="Answers are drawn only from your organisation's policies, the CSB templates and stored copies of monitored sources. It is not legal advice; every answer shows its sources so you can check them."
      />
      {!ai ? <div className="mb-4 border-l-2 border-amber-500 bg-amber-50/60 px-4 py-3 text-sm text-amber-800">AI is not configured. You will see matching search results without a written answer.</div> : null}
      {ai?.isSimulated ? <div className="mb-4 border-l-2 border-violet-500 bg-violet-50/60 px-4 py-3 text-sm text-violet-800">AI is running in simulated mode for this demonstration. Answers are templated from search results, not generated by a language model.</div> : null}
      <AssistantForm />
    </>
  );
}
