# Regenerates src/server/documents/fonts/coverage.ts from the embedded PDF fonts.
# Run with: python3 scripts/pdf-font-coverage.py  (needs fontTools: pip install fonttools)
from pathlib import Path
from fontTools.ttLib import TTFont

folder = Path(__file__).resolve().parent.parent / "src/server/documents/fonts"
sets = [set(TTFont(f).getBestCmap()) for f in sorted(folder.glob("*.ttf"))]
common = sorted(set.intersection(*sets))
ranges, start, prev = [], common[0], common[0]
for c in common[1:]:
    if c != prev + 1:
        ranges.append((start, prev))
        start = c
    prev = c
ranges.append((start, prev))
body = ",".join(f"[{a},{b}]" if a != b else f"[{a},{a}]" for a, b in ranges)
(folder / "coverage.ts").write_text(
    "// Generated by scripts/pdf-font-coverage.py: Unicode ranges every embedded PDF font can draw.\n"
    f"export const FONT_COVERAGE: readonly (readonly [number, number])[] = [{body}];\n"
)
print(len(common), "code points in", len(ranges), "ranges")
